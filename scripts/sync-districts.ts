import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { indianStates } from "../src/shared/india";

/**
 * Regenerates `src/shared/india-districts.ts` from a public district dataset so
 * the State -> District dropdowns are real data rather than a hand-typed list.
 *
 * Source: https://github.com/iaseth/data-for-india (MIT). The dataset carries
 * the 2022+ district split (Alluri Sitharama Raju, Anakapalli, ...) and includes
 * every state and union territory the platform supports.
 *
 * Usage: npm run districts:sync
 */

const SOURCE = "https://raw.githubusercontent.com/iaseth/data-for-india/master/data/minified/districts.min.json";

// The dataset uses a few long-form names; the platform stores the short forms
// from `indianStates`.
const stateAliases: Record<string, string> = {
  "Andaman and Nicobar": "Andaman and Nicobar Islands",
  "National Capital Territory of Delhi": "Delhi",
};

type SourceRow = { state: string; district: string };

async function main() {
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`Could not download the district dataset (${response.status}).`);
  const payload = (await response.json()) as { districts: SourceRow[] };

  const grouped = new Map<string, Set<string>>();
  for (const row of payload.districts) {
    const state = stateAliases[row.state] ?? row.state;
    const name = row.district.trim();
    if (!name) continue;
    if (!grouped.has(state)) grouped.set(state, new Set());
    grouped.get(state)!.add(name);
  }

  const missing = indianStates.filter((state) => !grouped.get(state)?.size);
  if (missing.length) throw new Error(`No districts for: ${missing.join(", ")}`);

  const unknown = [...grouped.keys()].filter((state) => !(indianStates as readonly string[]).includes(state));
  if (unknown.length) throw new Error(`Dataset has states the platform does not list: ${unknown.join(", ")}`);

  const lines: string[] = [];
  lines.push("// Generated by scripts/sync-districts.ts. Do not edit by hand.");
  lines.push("//");
  lines.push("// Source: https://github.com/iaseth/data-for-india (MIT licence).");
  lines.push("// Regenerate with: npm run districts:sync");
  lines.push("");
  lines.push('import type { indianStates } from "./india";');
  lines.push("");
  lines.push("export type IndianState = (typeof indianStates)[number];");
  lines.push("");
  lines.push("/** Districts as published by the source dataset, sorted per state. */");
  lines.push("export const districtsByState: Record<IndianState, readonly string[]> = {");
  let total = 0;
  for (const state of indianStates) {
    const districts = [...grouped.get(state)!.values()].sort((a, b) => a.localeCompare(b, "en-IN"));
    total += districts.length;
    lines.push(`  ${JSON.stringify(state)}: [${districts.map((name) => JSON.stringify(name)).join(", ")}],`);
  }
  lines.push("};");
  lines.push("");
  lines.push("/** Districts for a stored state, or an empty list for an unknown state. */");
  lines.push("export function districtsFor(state: string): readonly string[] {");
  lines.push("  return (districtsByState as Record<string, readonly string[]>)[state] ?? [];");
  lines.push("}");
  lines.push("");
  lines.push("export function isDistrictOfState(state: string, district: string): boolean {");
  lines.push("  return districtsFor(state).includes(district);");
  lines.push("}");
  lines.push("");

  const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "shared", "india-districts.ts");
  writeFileSync(target, lines.join("\n"), "utf8");
  console.log(`Wrote ${total} districts across ${indianStates.length} states and union territories.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
