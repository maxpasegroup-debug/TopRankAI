import { NextPaperNotice } from "@/components/platform/app/NextPaperNotice";
import { getPaperSchedule } from "@/server/platform/paper-schedule";
import { getCandidateExams } from "@/server/platform/candidate";
import Link from "next/link";
import { Icon, type IconName } from "@/components/platform/Icon";
import { NotificationActions } from "@/components/platform/app/NotificationActions";
import { requireAuth } from "@/server/auth/session";
import { getNotifications } from "@/server/platform/insights";
import { getSubscription } from "@/server/platform/subscriptions";
import { formatDateTime } from "@/server/platform/utils";

export const dynamic = "force-dynamic";
export const metadata = { title: "Notifications" };

const iconForType: Record<string, IconName> = {
  DAILY_EXAM: "calendar",
  MISSED_EXAM: "alert",
  ACHIEVEMENT: "trophy",
  PERFORMANCE: "chart",
  TARGET: "target",
  SYSTEM: "info",
  REVISION: "refresh",
};

export default async function NotificationsPage() {
  const user = await requireAuth();
  await getSubscription(user.id);
  const [items, exams] = await Promise.all([getNotifications(user.id), getCandidateExams(user.id)]);
  const schedules = await Promise.all(exams.map((exam) => getPaperSchedule(user.id, exam)));
  const unread = items.filter((item) => !item.readAt).length;

  return (
    <>
      <div className="tp-page-head">
        <div>
          <div className="tp-eyebrow">Inbox</div>
          <h1>Notifications</h1>
          <p>{unread} unread of {items.length}. These are generated by recorded activity, not marketing.</p>
        </div>
        <NotificationActions unread={unread} />
      </div>

      {exams.map((exam, index) => <NextPaperNotice key={exam.targetId} name={exam.shortName ?? exam.name} schedule={schedules[index]} />)}
      <div className="tp-card tp-card-pad">
        {items.length ? (
          items.map((item) => (
            <article className="tp-notice" key={item.id} data-unread={!item.readAt}>
              <span className="tp-notice-icon"><Icon name={iconForType[item.type] ?? "bell"} /></span>
              <div className="tp-grow">
                <div className="tp-row-between" style={{ alignItems: "flex-start" }}>
                  <div>
                    <h4>{item.title}</h4>
                    <p>{item.body}</p>
                  </div>
                  <div className="tp-stack tp-gap-8" style={{ alignItems: "flex-end" }}>
                    <time>{formatDateTime(item.createdAt)}</time>
                    {!item.readAt ? <NotificationActions unread={1} id={item.id} /> : null}
                  </div>
                </div>
                <div className="tp-row tp-gap-12 tp-mt-8">
                  {item.href ? (
                    <Link className="tp-link tp-small" href={item.href}>
                      Open <Icon name="arrow-right" size={13} style={{ display: "inline" }} />
                    </Link>
                  ) : null}
                  <span className="tp-xs tp-faint">{item.type.replace(/_/g, " ").toLowerCase()}</span>
                </div>
              </div>
            </article>
          ))
        ) : (
          <div className="tp-empty" style={{ border: 0, background: "transparent" }}>
            <span className="tp-feature-icon" style={{ margin: 0 }}><Icon name="bell" /></span>
            <h3>Nothing yet</h3>
            <p>Notifications appear when a daily paper is prepared, a badge unlocks or a result is recorded.</p>
            <Link className="tp-btn tp-btn-soft" href="/app/daily">Go to daily papers</Link>
          </div>
        )}
      </div>
    </>
  );
}
